import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const appRoot = new URL("../", import.meta.url);
const checkOnly = process.argv.slice(2).includes("--check");
const unexpectedArguments = process.argv
  .slice(2)
  .filter((argument) => argument !== "--check");

if (unexpectedArguments.length > 0) {
  throw new TypeError(`unexpected arguments: ${unexpectedArguments.join(", ")}`);
}

const readJson = (relativePath) =>
  JSON.parse(readFileSync(new URL(relativePath, appRoot), "utf8"));

const asRecord = (value) =>
  typeof value === "object" && value !== null ? value : undefined;

const componentRef = (schemaId, name) => ({
  $ref: `${schemaId}#/components/schemas/${name}`,
});

const componentArray = (schemaId, name) => ({
  type: "array",
  items: componentRef(schemaId, name),
});

const generatedHeader = `// @ts-nocheck
// Generated by scripts/generate-runtime-validators.mjs. Do not edit directly.
`;

const assertCspSafe = (source, destination) => {
  const forbidden = [
    ["CommonJS runtime import", /\brequire\s*\(/u],
    ["dynamic function construction", /\bFunction\s*\(/u],
    ["eval", /\beval\s*\(/u],
  ];
  for (const [description, pattern] of forbidden) {
    if (pattern.test(source)) {
      throw new TypeError(`${destination} contains ${description}`);
    }
  }
};

const generateModule = ({ document, schemaId, validatorNamespace, validators, suffix = "" }) => {
  const ajv = new Ajv2020({
    strict: false,
    allErrors: false,
    validateFormats: false,
    code: { source: true, esm: true, lines: true },
  });
  ajv.addSchema(document, schemaId);

  const exports = {};
  for (const [name, schema] of Object.entries(validators)) {
    const validatorId = `urn:trouve:${validatorNamespace}-validator:${name}`;
    ajv.addSchema({ $id: validatorId, ...schema });
    exports[name] = validatorId;
  }

  const body = standaloneCode(ajv, exports).trimEnd();
  const trailer = suffix.trimEnd();
  return `${generatedHeader}${body}${trailer === "" ? "" : `\n${trailer}`}\n`;
};

const protocolSchemaId = "urn:trouve:protocol-openapi";
const protocolDocument = readJson("src/generated/protocol-openapi.json");
const protocolSchemas = asRecord(asRecord(protocolDocument.components)?.schemas);

// JSON object keys are always strings. utoipa currently describes the keys of
// Rust maps keyed by u64 as integer-valued `propertyNames`, which rejects the
// wire representation (for example `{ "7": "openai/gpt-5.6" }`). Normalize
// those three thread-snapshot maps only in the runtime validator until the
// upstream schema generator can express numeric string keys directly.
const threadViewSnapshot = asRecord(protocolSchemas?.ThreadViewSnapshot);
const threadViewProperties = asRecord(threadViewSnapshot?.properties);
for (const name of ["turn_models", "turn_started_at", "turn_duration_ms"]) {
  const property = asRecord(threadViewProperties?.[name]);
  const propertyNames = asRecord(property?.propertyNames);
  if (propertyNames?.type === "integer") {
    property.propertyNames = { type: "string", pattern: "^(0|[1-9][0-9]*)$" };
  }
}
const eventEnvelope = asRecord(protocolSchemas?.EventEnvelope);
const eventEnvelopeAllOf = eventEnvelope?.allOf;
const eventEnvelopeFields = Array.isArray(eventEnvelopeAllOf)
  ? eventEnvelopeAllOf.find((candidate) => {
      const schema = asRecord(candidate);
      const properties = asRecord(schema?.properties);
      const required = schema?.required;
      return properties !== undefined
        && Array.isArray(required)
        && ["cursor", "scope", "ts"].every((field) =>
          required.includes(field) && properties[field] !== undefined
        );
    })
  : undefined;
if (eventEnvelopeFields === undefined) {
  throw new TypeError("protocol schema has no EventEnvelope fields");
}

const event = asRecord(protocolSchemas?.Event);
const eventVariants = event?.oneOf;
if (!Array.isArray(eventVariants)) {
  throw new TypeError("protocol schema has no Event variants");
}
const knownEventTypes = [];
for (const variant of eventVariants) {
  const properties = asRecord(asRecord(variant)?.properties);
  const typeSchema = asRecord(properties?.type);
  const values = typeSchema?.enum;
  if (!Array.isArray(values) || values.length !== 1 || typeof values[0] !== "string") {
    throw new TypeError("protocol Event variant has no single string discriminator");
  }
  knownEventTypes.push(values[0]);
}
if (new Set(knownEventTypes).size !== knownEventTypes.length) {
  throw new TypeError("protocol Event has duplicate discriminators");
}

