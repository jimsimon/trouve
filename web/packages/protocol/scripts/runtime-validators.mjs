// Shared helpers for compiling OpenAPI component schemas into standalone,
// CSP-safe AJV validators. The protocol package uses them for the server
// protocol; app-ui reuses them for the desktop host API.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

export const parseGeneratorArguments = (argv = process.argv.slice(2)) => {
  const checkOnly = argv.includes("--check");
  const unexpected = argv.filter((argument) => argument !== "--check");
  if (unexpected.length > 0) {
    throw new TypeError(`unexpected arguments: ${unexpected.join(", ")}`);
  }
  return { checkOnly };
};

export const readJson = (url) => JSON.parse(readFileSync(url, "utf8"));

export const asRecord = (value) =>
  typeof value === "object" && value !== null ? value : undefined;

export const componentRef = (schemaId, name) => ({
  $ref: `${schemaId}#/components/schemas/${name}`,
});

export const componentArray = (schemaId, name) => ({
  type: "array",
  items: componentRef(schemaId, name),
});

// Both owning packages expose the generator at this relative path.
const generatedHeader = `// @ts-nocheck
// Generated by scripts/generate-runtime-validators.mjs. Do not edit directly.
`;

export const assertCspSafe = (source, destination) => {
  const forbidden = [
    ["CommonJS runtime import", /\brequire\s*\(/u],
    ["dynamic function construction", /\bFunction\s*\(/u],
    ["eval", /\beval\s*\(/u],
  ];
  for (const [description, pattern] of forbidden) {
    if (pattern.test(source)) {
      throw new TypeError(`${destination} contains ${description}`);
    }
  }
};

export const generateModule = ({
  document,
  schemaId,
  validatorNamespace,
  validators,
  suffix = "",
}) => {
  const ajv = new Ajv2020({
    strict: false,
    allErrors: false,
    validateFormats: false,
    // The OpenAPI graph deliberately reuses many protocol components across
    // response validators. Keeping refs as shared functions avoids emitting
    // the same nested validation branches into every root validator.
    inlineRefs: false,
    code: { source: true, esm: true, lines: true },
  });
  ajv.addSchema(document, schemaId);

  const exports = {};
  for (const [name, schema] of Object.entries(validators)) {
    const validatorId = `urn:trouve:${validatorNamespace}-validator:${name}`;
    ajv.addSchema({ $id: validatorId, ...schema });
    exports[name] = validatorId;
  }

  const body = standaloneCode(ajv, exports).trimEnd();
  const trailer = suffix.trimEnd();
  return `${generatedHeader}${body}${trailer === "" ? "" : `\n${trailer}`}\n`;
};

/** Write or verify generated modules. `outputs` maps package-relative paths to
 * source text; `packageRoot` is the URL of the owning package directory. */
export const writeGeneratedModules = ({ outputs, packageRoot, checkOnly, regenerateCommand }) => {
  for (const [relativePath, source] of outputs) {
    assertCspSafe(source, relativePath);
    const destination = new URL(relativePath, packageRoot);
    if (!checkOnly) {
      writeFileSync(destination, source);
      continue;
    }
    let current;
    try {
      current = readFileSync(destination, "utf8");
    } catch {
      current = undefined;
    }
    if (current !== source) {
      console.error(`${fileURLToPath(destination)} is stale; run ${regenerateCommand}`);
      process.exitCode = 1;
    }
  }
};
